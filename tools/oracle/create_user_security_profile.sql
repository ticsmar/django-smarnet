-- Criacao da tabela DJANGO_API.USER_SECURITY_PROFILE
-- com vinculo de usuario local (AUTH_USER) e usuario legado (SIAOS.USUARIO).

-- Grants necessarios para criar FKs cruzando schemas.
GRANT SELECT, REFERENCES ON DJANGO_API.AUTH_USER TO DJANGO_API;
GRANT SELECT, REFERENCES ON SIAOS.USUARIO TO DJANGO_API;

CREATE TABLE DJANGO_API.USER_SECURITY_PROFILE (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  USER_ID NUMBER(11) NOT NULL,
  MUST_CHANGE_PASSWORD NUMBER(1) DEFAULT 0 NOT NULL,
  USU_CHAPA NUMBER(5),
  CONSTRAINT PK_USER_SECURITY_PROFILE PRIMARY KEY (ID),
  CONSTRAINT UQ_USP_USER_ID UNIQUE (USER_ID),
  CONSTRAINT CK_USP_MUST_CHANGE_PASSWORD CHECK (MUST_CHANGE_PASSWORD IN (0, 1)),
  CONSTRAINT FK_USP_AUTH_USER FOREIGN KEY (USER_ID)
    REFERENCES DJANGO_API.AUTH_USER (ID),
  CONSTRAINT FK_USP_USU_CHAPA FOREIGN KEY (USU_CHAPA)
    REFERENCES SIAOS.USUARIO (USU_CHAPA)
);

CREATE INDEX IDX_USP_USU_CHAPA ON DJANGO_API.USER_SECURITY_PROFILE (USU_CHAPA);

COMMENT ON TABLE DJANGO_API.USER_SECURITY_PROFILE IS
  'Perfil de seguranca complementar do usuario Django com vinculos legados.';

COMMENT ON COLUMN DJANGO_API.USER_SECURITY_PROFILE.USER_ID IS
  'FK para AUTH_USER.ID (vinculo 1:1).';
COMMENT ON COLUMN DJANGO_API.USER_SECURITY_PROFILE.MUST_CHANGE_PASSWORD IS
  '0 = nao obrigar troca de senha; 1 = obrigar troca no proximo login.';
COMMENT ON COLUMN DJANGO_API.USER_SECURITY_PROFILE.USU_CHAPA IS
  'FK para SIAOS.USUARIO.USU_CHAPA (chapa do usuario legado).';
