  ADD CONSTRAINT FK_USP_AUTH_USER
  FOREIGN KEY (USER_ID)
  REFERENCES DJANGO_API.AUTH_USER (ID);

ALTER TABLE DJANGO_API.USER_SECURITY_PROFILE
  ADD CONSTRAINT FK_USP_USU_CHAPA
  FOREIGN KEY (USU_CHAPA)
  REFERENCES SIAOS.USUARIO (USU_CHAPA);
