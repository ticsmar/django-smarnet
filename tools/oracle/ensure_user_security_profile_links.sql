-- Adequacao de USER_SECURITY_PROFILE para vinculos de usuario em producao
-- Executar com usuario com privilegio para ALTER no schema DJANGO_API e GRANT nos schemas origem.

GRANT SELECT, REFERENCES ON SIAOS.USUARIO TO DJANGO_API;

ALTER TABLE DJANGO_API.USER_SECURITY_PROFILE
  ADD (
    USU_CHAPA NUMBER(5)
  );

